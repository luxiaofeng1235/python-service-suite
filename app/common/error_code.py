"""
============================================
业务错误码枚举
============================================
统一业务错误码定义，前端可根据 code 做差异化处理。
"""

from enum import IntEnum


class ErrorCode(IntEnum):
    """业务错误码枚举

    编码规则：
        10xx — 认证/登录相关
        11xx — 用户相关
        20xx — CMS/文章相关
        30xx — 文件相关
        40xx — 权限相关
        50xx — 系统相关
        60xx — 限流相关
    """

    # ==================== 认证 (10xx) ====================
    AUTH_INVALID_CREDENTIALS = 1001
    """用户名或密码错误"""
    AUTH_DISABLED = 1002
    """账号已禁用"""
    AUTH_RATE_LIMITED = 1003
    """登录过于频繁"""
    AUTH_CAPTCHA_ERROR = 1004
    """验证码错误"""
    AUTH_TOKEN_INVALID = 1005
    """Token 无效或已过期"""

    # ==================== 用户 (11xx) ====================
    USER_NOT_FOUND = 1101
    """用户不存在"""
    USER_DUPLICATE = 1102
    """用户已存在（用户名/邮箱重复）"""

    # ==================== CMS (20xx) ====================
    CMS_ARTICLE_NOT_FOUND = 2001
    """文章不存在"""
    CMS_CATEGORY_NOT_FOUND = 2002
    """分类不存在"""
    CMS_SLUG_DUPLICATE = 2003
    """URL 别名已存在"""
    CMS_TAG_NOT_FOUND = 2004
    """标签不存在"""
    CMS_TAG_DUPLICATE = 2005
    """标签名已存在"""

    # ==================== 文件 (30xx) ====================
    FILE_NOT_FOUND = 3001
    """文件记录不存在"""

    # ==================== 权限 (40xx) ====================
    PERMISSION_DENIED = 4001
    """无权限访问"""

    # ==================== 系统 (50xx) ====================
    SYSTEM_EMAIL_NOT_CONFIGURED = 5001
    """系统未配置邮件发送功能"""
    SYSTEM_EMAIL_SEND_FAILED = 5002
    """邮件发送失败"""

    # ==================== 限流 (60xx) ====================
    RATE_LIMITED = 6001
    """请求过于频繁"""
